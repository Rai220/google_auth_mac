    // English source strings are also the fallback for unsupported system languages.
    public static func text(_ key: String, _ arguments: String..., language: AppLanguage = .saved()) -> String {
        render(key, arguments: arguments, language: language)
    }
    public static func render(_ key: String, arguments: [String], language: AppLanguage) -> String {
        let template = language.resolved() == .ru ? russian[key] ?? key : key
        // Replace placeholders in one pass so account names are never interpreted as templates.
        let source = template as NSString
        var result = template
        for match in placeholder.matches(in: template, range: NSRange(location: 0, length: source.length)).reversed() {
            if let index = Int(source.substring(with: match.range(at: 1))), arguments.indices.contains(index),
               let range = Range(match.range, in: result) { result.replaceSubrange(range, with: arguments[index]) }
        }
        return result
    }
